export function generateStaticParams() {
  return Object.keys(policies).map((slug) => ({ slug }));
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ slug: string }>;
}): Promise<Metadata> {
  const { slug } = await params;
  const policy = policies[slug];
  if (!policy) return { title: "صفحة غير موجودة" };
  return { title: policy.title, description: policy.summary };
}

/** صفحات السياسات — صياغة مبدئية تُراجع قانونياً قبل النشر */
export default async function PolicyPage({
  params,
}: {
  params: Promise<{ slug: string }>;
}) {
  const { slug } = await params;
  const policy = policies[slug];
  /* Checkpoint 7: النص الثابت للـ SSR — والعميل يستبدله بنص الـ CMS المنشور */
  if (!policy) notFound();
  return <PolicyView slug={slug} staticPolicy={policy} />;
}
