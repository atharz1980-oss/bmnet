type IconComponent = React.ComponentType<{ className?: string }>;

const LUCIDE: Partial<Record<SocialPlatform, IconComponent>> = {
  instagram: Instagram,
  email: Mail,
  youtube: Youtube,
  facebook: Facebook,
  linkedin: Linkedin,
  telegram: Send,
  website: Globe,
};

export function SocialIcon({
  platform,
  className,
}: {
  platform: SocialPlatform;
  className?: string;
}) {
  const Lucide = LUCIDE[platform];
  if (Lucide) return <Lucide className={cn("h-4 w-4", className)} />;
  const path = GLYPHS[platform];
  /* منصة بلا أيقونة معروفة تعود إلى رمز الرابط العام بدل الاختفاء. */
  if (!path) return <Globe className={cn("h-4 w-4", className)} />;
  return <Glyph className={className} path={path} />;
}

interface SocialIconsProps {
  items: { id: SocialPlatform; label: string; href: string }[];
  className?: string;
  iconClassName?: string;
}

export function SocialIcons({ items, className, iconClassName }: SocialIconsProps) {
  return (
    <div className={cn("flex items-center gap-1", className)}>
      {items.map((item) => (
        <a
          key={item.id}
          href={item.href}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={item.label}
          title={item.label}
          className={cn(
            "inline-flex h-9 w-9 items-center justify-center rounded-full text-charcoal-500 transition-colors hover:bg-brand-50 hover:text-brand-600 focus-visible:ring-2 focus-visible:ring-brand-600/40",
            iconClassName,
          )}
        >
          <SocialIcon platform={item.id} className="h-4 w-4" />
        </a>
      ))}
    </div>
  );
}
