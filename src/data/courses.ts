/* ------- دوال مساعدة للوصول للبيانات (جاهزة للربط بقاعدة بيانات لاحقاً) ------- */

export function getCourseBySlug(slug: string): Course | undefined {
  return courses.find((course) => course.slug === slug);
}

export function getPublishedCourses(): Course[] {
  return courses.filter((course) => course.published);
}

export function getFeaturedCourses(): Course[] {
  return getPublishedCourses().filter((course) => course.featured);
}

export function getCoursesByCategory(category: string): Course[] {
  return getPublishedCourses().filter((course) => course.category === category);
}

/** الدورة القادمة: أول دورة حضورية لأفراد لديها جلسة قادمة */
export function getUpcomingCourse(): Course | undefined {
  const now = new Date();
  return (
    getPublishedCourses()
      .filter((course) => course.upcomingSessions.length > 0)
      .sort((a, b) => {
        const aDate = new Date(`${a.upcomingSessions[0].startDate}T12:00:00`).getTime();
        const bDate = new Date(`${b.upcomingSessions[0].startDate}T12:00:00`).getTime();
        return aDate - bDate;
      })
      .find((course) => new Date(`${course.upcomingSessions[0].startDate}T12:00:00`) > now) ??
    getCourseBySlug("photography-fundamentals")
  );
}
