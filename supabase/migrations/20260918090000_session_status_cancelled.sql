-- «ملغاة» قيمة مستقلة في حالة الدفعة.
--
-- لماذا لا نكتفي بـ«closed»: الإغلاق يعني «انتهى التسجيل» والدفعة قائمة،
-- والإلغاء يعني «لن تنعقد». تحميل المعنيين على قيمة واحدة يجعل الفرق
-- اصطلاحًا في رأس الموظف لا حقيقة في القاعدة، ويمنع أي حارس من التفريق.
--
-- منفصلة عن الترحيل التالي عمدًا: `alter type … add value` لا تُستعمل
-- قيمتها الجديدة داخل المعاملة نفسها، فتُطبَّق أولًا وحدها.
alter type public.session_status add value if not exists 'cancelled';
